import { useEffect, useState, type ReactNode } from 'react';

/* ─────────────────────────────────────────────────────────────────────────
 * Standard CLM page chrome — cyan-gradient header strip + expandable
 * "What We Are Doing Here" steps card. Every CLM master page renders
 * these two cards above its tabs/table card.
 *
 * Mirrors Card 1 + Card 2 from the CLM-Master.html prototype.
 * ───────────────────────────────────────────────────────────────────────── */

export type ClmHeaderProps = {
  /** SVG icon (white stroke, 19×19 typical) rendered in the gradient ico */
  icon:      ReactNode;
  /** Page title shown in the header card */
  title:     string;
  /** One-line subtitle below the title */
  sub:       string;
  /** "Add X" button label — pass null/empty to hide the button */
  addLabel?: string;
  onAdd?:    () => void;
  /** Extra class on the Add button (e.g. for a page-specific hover effect) */
  addClassName?: string;
  /** Optional extra control to render on the right side (e.g. tab pills) */
  rightSlot?: ReactNode;
};

export function ClmPageHeader({ icon, title, sub, addLabel, onAdd, addClassName, rightSlot }: ClmHeaderProps) {
  // Flag the <body> while a CLM master page is mounted. Global chrome that
  // lives OUTSIDE the page (e.g. the app footer, which can't be reached by a
  // `.clm-root` selector) is themed via `body.clm-active …`, and this class is
  // removed on unmount so non-CLM pages (HR, Sales, …) revert reliably.
  useEffect(() => {
    document.body.classList.add('clm-active');
    return () => document.body.classList.remove('clm-active');
  }, []);
  return (
    <div className="clm-head-strip">
      <div className="clm-head-strip-left">
        <div className="clm-head-strip-ico-wrap">
          <div className="clm-head-strip-ico">{icon}</div>
          <span className="clm-head-strip-dot" />
        </div>
        <div className="clm-head-strip-text">
          <div className="clm-head-strip-title">{title}</div>
          <div className="clm-head-strip-sub">{sub}</div>
        </div>
      </div>
      {rightSlot}
      {addLabel && onAdd && (
        <button className={`clm-add-btn ${addClassName ?? ''}`} onClick={onAdd}>
          <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="#fff" strokeWidth="2.6" strokeLinecap="round" strokeLinejoin="round">
            <line x1="12" y1="5" x2="12" y2="19" /><line x1="5" y1="12" x2="19" y2="12" />
          </svg>
          {addLabel}
        </button>
      )}
    </div>
  );
}

export type ClmStep = {
  /** "01", "02", "03" — usually 2-digit zero-padded */
  n:     string;
  title: string;
  desc:  string;
  /** SVG icon (currentColor stroke, 11×11 typical) */
  icon:  ReactNode;
};

export type ClmBrefBoxProps = {
  /** Small uppercase eyebrow label (e.g. "Segment Master") */
  label: string;
  /** Short subtitle next to the title (e.g. "Manage segment-wise…") */
  sub:   string;
  /** Step tiles — usually 4–5 items */
  steps: ClmStep[];
  /** SVG icon for the rounded badge in the header (white stroke, 13×13) */
  icon:  ReactNode;
  /** Whether the box starts collapsed (defaults to expanded) */
  defaultCollapsed?: boolean;
};

export function ClmBrefBox({ label, sub, steps, icon, defaultCollapsed = false }: ClmBrefBoxProps) {
  const [collapsed, setCollapsed] = useState(defaultCollapsed);
  return (
    <div className="clm-page-card">
      <div className={`clm-bref ${collapsed ? 'collapsed' : ''}`}>
        <div className="clm-bref-head" onClick={() => setCollapsed(v => !v)}>
          <div className="clm-bref-ico">{icon}</div>
          <div className="clm-bref-mid">
            <div className="clm-bref-row">
              <div className="clm-bref-label">{label}</div>
              <div className="clm-bref-sep" />
              <div className="clm-bref-title">What We Are Doing Here</div>
            </div>
            <div className="clm-bref-sub">{sub}</div>
          </div>
          <div className="clm-bref-toggle">
            <svg width="10" height="10" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.8" strokeLinecap="round" strokeLinejoin="round">
              <polyline points="6 9 12 15 18 9" />
            </svg>
          </div>
        </div>
        <div className="clm-bref-body">
          {steps.map((s, i) => (
            <div className="clm-bref-item" key={i}>
              <div className="clm-bref-item-top">
                <div className="clm-bref-item-ico">{s.icon}</div>
                <span className="clm-bref-item-num">Step {s.n}</span>
              </div>
              <div className="clm-bref-item-title">{s.title}</div>
              <div className="clm-bref-item-desc">{s.desc}</div>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}

