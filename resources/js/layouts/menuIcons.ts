/** The icon a menu entry names, or Circle when it names nothing we have. */
export function getMenuIcon(name?: string): LucideIcon {
  if (!name) return Circle;

  const icon = ICONS[name];
  if (icon) return icon;

  /* The one cost of naming the set: a menu entry can now reference an icon
     that is not in this file, and it will quietly render a Circle. That used
     to be impossible — the namespace import held every icon there was — so
     say so out loud while developing. Stripped from the production bundle by
     the import.meta.env.DEV check. */
  if (import.meta.env.DEV) {
    console.warn(
      `[menuIcons] "${name}" is not in the icon map, so it renders as a Circle. ` +
      `Add it to resources/js/layouts/menuIcons.ts.`,
    );
  }

  return Circle;
}

export { Circle };
